"""SceneScript API coverage: members of WE's editor typings vs Diorama's prelude.

Usage:
    python tools/refcap/scenescript_coverage.py <lib.sceneScript.d.ts> > docs/re-notes/scenescript-api.md

Lists every member of the host-provided interfaces (the math classes come from
WE's own baseclasses.js and are not counted) and whether Diorama's
`crates/diorama-script/src/prelude.js` defines it: "yes" (implemented),
"stub" (exists, does nothing yet) or "—". Stubs are listed in STUBS below.
Only member names are read from the typings.
"""

import os
import re
import sys

HOST = [
    "IComponent", "IEffect", "ITextureAnimation", "IEffectLayer", "ITextLayer",
    "IImageLayer", "IParticleSystem", "ILayer", "IScene", "IConsole", "IInput",
    "ILocalStorage", "IEngine", "IAnimation",
]
# Present in the prelude but without real behaviour yet.
STUBS = {
    "getVideoTexture", "getAnimationLayer", "getAnimationLayerCount",
    "setMaterialProperty", "executeMaterialFunction", "getMaterial", "parallaxDepth",
    "play", "pause", "stop", "isPlaying", "emit", "instance",
    "getCameraTransforms", "openUserShortcut", "registerAsset",
    "getTransformMatrix",
    # Component callbacks the host never raises yet.
    "resizeScreen", "applyGeneralSettings",
    "destroy",
}
# Real on these interfaces although the same names are stubs elsewhere.
IMPLEMENTED = {("ITextureAnimation", m) for m in ("play", "pause", "stop", "isPlaying")}
# Component callbacks the host calls.
CALLED = {"init", "update", "applyUserProperties", "cursorEnter", "cursorLeave",
          "cursorMove", "cursorDown", "cursorUp", "cursorClick", "mediaStatusChanged",
          "mediaPlaybackChanged", "mediaPropertiesChanged", "mediaThumbnailChanged",
          "mediaTimelineChanged"}


def members(dts):
    out = {}
    current = None
    depth = 0
    for line in dts.splitlines():
        m = re.match(r"\s*(?:declare\s+)?(?:interface|class)\s+(\w+)", line)
        if m and depth == 0:
            current = m.group(1)
            out.setdefault(current, [])
        if current and depth == 1:
            mm = re.match(r"\s*(?:readonly\s+|static\s+|get\s+|set\s+)*(\w+)\s*[\(:?]", line)
            if mm and mm.group(1) not in out[current]:
                out[current].append(mm.group(1))
        depth += line.count("{") - line.count("}")
        if depth == 0:
            current = None
    return out


def main():
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    dts = open(sys.argv[1], encoding="utf-8").read()
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    prelude = "".join(
        open(os.path.join(root, "crates/diorama-script/src", f), encoding="utf-8").read()
        for f in ("prelude.js", "lib.rs")
    )
    table = members(dts)
    total = done = stub = 0
    print("# SceneScript API coverage\n")
    print("Generated by `tools/refcap/scenescript_coverage.py` from WE's editor typings "
          "(member names only) against `crates/diorama-script/src/prelude.js` and `lib.rs`. "
          "Math classes (`Vec2/3/4`, `Mat3/4`) come from WE's own `baseclasses.js`.\n")
    rows = []
    for name in HOST:
        for m in table.get(name, []):
            if name == "IComponent":
                status = "yes" if m in CALLED else ("stub" if m in STUBS else "—")
            elif m in STUBS and (name, m) not in IMPLEMENTED:
                status = "stub" if re.search(r"\b%s\b" % re.escape(m), prelude) else "—"
            else:
                status = "yes" if re.search(r"\b%s\b" % re.escape(m), prelude) else "—"
            total += 1
            done += status == "yes"
            stub += status == "stub"
            rows.append((name, m, status))
    print("**%d of %d members implemented, %d stubbed, %d missing.**\n"
          % (done, total, stub, total - done - stub))
    print("| Interface | Member | Status |")
    print("|---|---|---|")
    for name, m, status in rows:
        print("| %s | `%s` | %s |" % (name, m, status))


main()
